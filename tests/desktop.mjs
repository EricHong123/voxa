import {_electron as electron,expect} from '@playwright/test';
import {mkdtemp,mkdir,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
const directory=await mkdtemp(path.join(tmpdir(),'voiceleaf-desktop-'));
await mkdir('artifacts',{recursive:true});
let app;
try{
 app=await electron.launch({args:['.'],env:{...process.env,VOICELEAF_DATA_DIR:directory,VOICELEAF_TEST:'1'}});
 await expect.poll(()=>app.windows().some(p=>p.url().endsWith('index.html')),{timeout:15000}).toBe(true);
 const page=app.windows().find(p=>p.url().endsWith('index.html'));const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await expect(page.getByRole('heading',{name:'让想法，自然流动。'})).toBeVisible();
 await page.screenshot({path:'artifacts/home.png',fullPage:true});
 await page.getByRole('button',{name:'个人词典',exact:true}).click();
 await page.getByRole('textbox',{name:'新词汇'}).fill('声笺测试');await page.getByRole('button',{name:'添加词汇',exact:true}).click();
 await expect(page.locator('.word').filter({hasText:'声笺测试'})).toBeVisible();
 await page.getByRole('button',{name:'设置',exact:true}).click();
 await expect(page.getByRole('heading',{name:'按你的习惯来。'})).toBeVisible();
 await page.getByRole('switch',{name:'智能整理',exact:true}).click();await page.getByRole('button',{name:'保存设置'}).click();
 await expect(page.getByRole('status')).toHaveText('设置已保存');
 const stored=await page.evaluate(()=>window.voiceleaf.read());expect(stored.value.settings.polish).toBe(false);
 const blocked=await page.evaluate(()=>window.voiceleaf.settings({whisperUrl:'https://example.com'}));expect(blocked.ok).toBe(false);
 const frameDenied=await app.evaluate(async({BrowserWindow})=>{const wins=BrowserWindow.getAllWindows();const hud=wins.find(w=>w.webContents.getURL().endsWith('#hud'));return hud.webContents.executeJavaScript('window.voiceleaf.read().then(()=>false,()=>true)');});expect(frameDenied).toBe(true);
 await page.screenshot({path:'artifacts/settings.png',fullPage:true});
 await page.getByRole('button',{name:'个人词典',exact:true}).click();await page.getByRole('button',{name:'删除 声笺测试'}).click();await expect(page.locator('.word')).toHaveCount(0);

 const hud=app.windows().find(p=>p.url().endsWith('#hud'));
 const emit=async events=>app.evaluate(({BrowserWindow},events)=>{const win=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('#hud'));for(const event of events)win.webContents.send('voiceleaf:event',event);},events);
 await emit([{type:'phase',phase:'recording'},{type:'target',name:'测试输入框',ready:true},{type:'hud-notice',message:''}]);
 await expect(hud.getByRole('status')).toHaveText('正在聆听');
 await expect.poll(()=>app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('#hud')).getSize()[1])).toBe(76);
 await hud.screenshot({path:'artifacts/hud-compact.png'});
 await emit([{type:'preview',text:'嗯，那个，明天九点开会，我们一起讨论新的方案。'}]);
 await expect(hud.locator('.hud-preview')).toContainText('明天九点');
 await hud.screenshot({path:'artifacts/hud-preview.png'});
 await emit([{type:'revision',value:{original:'嗯，那个，明天九点开会。',text:'明天九点开会。'}},{type:'hud-notice',message:'无法读取目标输入框，请复制文字粘贴。',canCopy:true,status:'retained'},{type:'phase',phase:'idle'}]);
 await expect(hud.getByRole('status')).toHaveText('文字已保留');
 await expect(hud.getByRole('button',{name:'复制文字'})).toBeVisible();
 await expect(hud.getByRole('button',{name:'前往设置'})).toHaveCount(0);
 await expect(hud.locator('.revision-delete')).toHaveCount(0);
 await hud.screenshot({path:'artifacts/hud-fallback.png'});
 await emit([{type:'hud-notice',message:'已填入 测试输入框',canCopy:true,status:'inserted'}]);
 await expect(hud.getByRole('status')).toHaveText('已填入');
 await hud.screenshot({path:'artifacts/hud-inserted.png'});
 await emit([{type:'hud-notice',message:'需要辅助功能权限',permission:true}]);
 await hud.getByRole('button',{name:'前往设置'}).click();
 await expect(page.getByRole('heading',{name:'按你的习惯来。'})).toBeVisible();
 await page.getByRole('button',{name:'测试填入',exact:true}).click();
 await expect(hud.getByRole('status')).toHaveText('请选择输入框');
 await expect(hud.locator('.hud-message')).toContainText('秒后填入');
 await hud.getByRole('button',{name:'取消',exact:true}).click();
 await expect(page.getByRole('button',{name:'测试填入',exact:true})).toBeEnabled();
 const afterCancel=await page.evaluate(()=>window.voiceleaf.read());expect(afterCancel.value.history.length).toBe(0);
 await page.getByRole('button',{name:'测试实时填入',exact:true}).click();
 await expect(hud.getByRole('status')).toHaveText('请选择输入框');
 await hud.getByRole('button',{name:'取消',exact:true}).click();
 await expect(page.getByRole('button',{name:'测试实时填入',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'首页',exact:true}).click();
 await page.getByRole('button',{name:'开始录音',exact:true}).click();
 await expect(hud.locator('.hud-message')).toContainText('秒后开始聆听');
 await hud.getByRole('button',{name:'取消',exact:true}).click();
 await expect(page.getByRole('button',{name:'开始录音',exact:true})).toBeEnabled();

 expect(errors).toEqual([]);console.log('Desktop passed: navigation, dictionary CRUD, settings persistence, local-only URL validation, HUD privilege isolation, no renderer errors.');
 await writeFile('artifacts/desktop-results.json',JSON.stringify({passed:true,rendererErrors:errors},null,2));
}finally{await app?.close();await rm(directory,{recursive:true,force:true});}
